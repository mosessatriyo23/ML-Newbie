type Raw = [title: string, difficulty?: Difficulty, id?: string];

function slug(s: string): string {
  return s
    .toLowerCase()
    .replace(/²/g, "2")
    .replace(/[`()[\]?.,'"]/g, "")
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function mod(
  id: string,
  number: string,
  title: string,
  description: string,
  skill: Skill,
  phase: 1 | 2 | 3 | 4,
  prefix: string,
  lessons: (string | Raw)[],
): ModuleMeta {
  return {
    id,
    number,
    title,
    description,
    skill,
    phase,
    lessons: lessons.map((l): LessonMeta => {
      const [t, d, explicitId] = typeof l === "string" ? [l] : l;
      return { id: explicitId ?? `${prefix}-${slug(t)}`, title: t, moduleId: id, difficulty: d ?? "beginner" };
    }),
  };
}

